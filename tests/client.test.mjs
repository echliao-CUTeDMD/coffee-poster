import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
const memory=new Map();
const ctx=vm.createContext({URL,crypto:webcrypto,Date,localStorage:{getItem:k=>memory.get(k),setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)},setTimeout:()=>1,clearTimeout(){},clearInterval(){}});
vm.runInContext(await readFile(new URL('../cloud-client.js',import.meta.url),'utf8'),ctx);
const api=ctx.ShenkengCloud;
assert.equal(api.configured,false);
assert.equal(api.clean({visited:{},completed:'bad'}).completed.length,0);
assert.equal(api.merge({completed:['river']},{completed:['river','people']}).completed.length,2);
assert.ok(api.csv([['=1+1','"quoted"']],['a','b']).includes('"\'=1+1"'));
const statuses=[];const store=new api.PlayerStore({name:'測試',role:'student'},'test',s=>statuses.push(s),()=>{});
store.connected=true;store.epoch=0;let fail=true;
store.client={rpc:async(_,p)=>fail?{error:Error('offline')}:{data:{progress:p.p_progress,epoch:p.p_epoch,reset_detected:false}},auth:{stopAutoRefresh(){}}};
store.event('explore','site:river');await store.flush();assert.equal(store.queue.length,1);assert.ok(statuses.at(-1).includes('尚未同步'));
fail=false;await store.flush();assert.equal(store.queue.length,0);
store.event('answer','river',{correct:true});
let finish;store.client.rpc=()=>new Promise(r=>finish=r);const pending=store.flush();store.reset();finish({data:{progress:{visited:['old'],completed:['river']},epoch:0,reset_detected:false}});await pending;
assert.equal(store.resetPending,true);assert.equal(store.state.completed.length,0);assert.equal(store.queue[0].event_type,'reset');
store.client.rpc=async()=>({data:{progress:{visited:[],completed:[],active:null},epoch:1,reset_detected:false}});await store.flush();assert.equal(store.resetPending,false);assert.equal(store.epoch,1);
store.close();console.log('PASS: progress validation, merge, CSV escaping, offline queue/retry and reset during in-flight sync.');
